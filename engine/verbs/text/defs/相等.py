"""两段文本完全一样返回「是」，否则「否」。例如 设 same = 相等 {甲} {乙}

跟「如果 {甲} 等于 {乙}」的差别：条件现在在原文上拆、两边分别展开，值里有
空格、是空的、或者是「包含」「为空」这类词都不怕了；但「等于」会去掉两头的
空白再比。这个动词一个字一个字地比，不去空白、不归一化，要宽松比较先「归一化」。
"""


def 相等(甲: str = "", 乙: str = "") -> str:
    return "是" if str(甲 if 甲 is not None else "") == str(乙 if 乙 is not None else "") else "否"
